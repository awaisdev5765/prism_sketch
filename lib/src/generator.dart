import 'spec.dart';

/// Generates idiomatic prism_kit Flutter code from a [SketchSpec].
///
/// The output is a complete, compilable Dart file: one StatefulWidget per
/// screen, imports wired to `package:prism_kit/prism.dart`, interactive
/// state for controls, and TODO markers exactly where the developer's
/// business logic belongs. Meant to be pasted and edited, not final.
class CodeGenerator {
  /// Generates the full Dart file for [spec].
  String generate(SketchSpec spec) {
    final body = _body(spec);
    final usesState = _needsState(spec);
    final head = _header(spec);
    return head +
        (usesState ? _statefulClass(spec, body) : _statelessClass(spec, body));
  }

  bool _needsState(SketchSpec spec) => spec.components.any(
        (c) => switch (c.kind) {
          'switch' ||
          'slider' ||
          'checkbox' ||
          'dropdown' ||
          'text_field' ||
          'email_field' ||
          'password_field' ||
          'rating' ||
          'calendar' ||
          'file_picker' ||
          'image_picker' => true,
          _ => false,
        },
      );


  /// State field declarations for every interactive component.
  String _body(SketchSpec spec) {
    final fields = <String>[];
    for (final c in spec.components) {
      final label = c.label ?? '';
      switch (c.kind) {
        case 'switch':
          fields.add("  bool _${_camel(label)}Enabled = false;" "\n");
        case 'checkbox':
          fields.add("  bool _${_camel(label)}Checked = false;" "\n");
        case 'slider':
          fields.add("  double _${_camel(label)}Value = 0.5;" "\n");
        case 'dropdown':
          fields.add("  String _${_camel(label)}Value = 'one';" "\n");
        case 'rating':
          if (!fields.any((f) => f.contains('_rating'))) {
            fields.add("  double _rating = 0;" "\n");
          }
        case 'calendar':
          if (!fields.any((f) => f.contains('_focusedMonth'))) {
            fields.add("  DateTime _focusedMonth = DateTime.now();" "\n");
            fields.add("  final Set<DateTime> _selectedDays = {};" "\n");
          }
        case 'file_picker':
          if (!fields.any((f) => f.contains('_files'))) {
            fields.add("  final List<PrismPickedFile> _files = [];" "\n");
          }
        case 'image_picker':
          if (!fields.any((f) => f.contains('_images'))) {
            fields.add("  final List<PrismPickedFile> _images = [];" "\n");
          }
      }
    }
    return fields.join();
  }

  String _header(SketchSpec spec) => '''
// Generated by prism_sketch — a starting point, not a finish line.
//
// Every component reads PrismTokens and PrismColors, so dropping your
// theme onto MaterialApp styles the whole screen.
import 'package:flutter/material.dart';
import 'package:prism_kit/prism.dart';

''';

  String _statefulClass(SketchSpec spec, String body) => '''
class ${spec.className} extends StatefulWidget {
  const ${spec.className}({super.key});

  @override
  State<${spec.className}> createState() => _${spec.className}State();
}

class _${spec.className}State extends State<${spec.className}> {
$body
  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(title: const Text('${spec.title}')),
      body: ${_bodyContainer(spec)},
      ${_fabLine(spec)}
    );
  }
}
''';

  String _statelessClass(SketchSpec spec, String body) => '''
class ${spec.className} extends StatelessWidget {
  const ${spec.className}({super.key});

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(title: const Text('${spec.title}')),
      body: ${_bodyContainer(spec)},
      ${_fabLine(spec)}
    );
  }
}
''';

  String _fabLine(SketchSpec spec) =>
      spec.components.any((c) => c.kind == 'fab')
          ? 'floatingActionButton: FloatingActionButton(onPressed: () {}, child: const Icon(Icons.add)),'
          : '';

  String _bodyContainer(SketchSpec spec) =>
      "ListView(\n        padding: const EdgeInsets.all(16),\n        children: [\n${_componentBody(spec)}\n        ],\n      )";

  String _componentBody(SketchSpec spec) {
    final lines = <String>[];
    var fieldCount = 0;
    for (final c in spec.components) {
      if (c.kind == 'text_field' ||
          c.kind == 'email_field' ||
          c.kind == 'password_field') {
        fieldCount++;
      }
      lines.addAll(_componentLines(c, spec, fieldCount));
    }
    return lines.join('\n');
  }

  List<String> _componentLines(
    SpecComponent c,
    SketchSpec spec,
    int fieldIndex,
  ) {
    final label = c.label ?? '';
    switch (c.kind) {
      case 'email_field':
        return [
          "            PrismTextField.email(",
          "              name: 'email',",
          "              label: 'Email',",
          "            ),",
        ];
      case 'password_field':
        return [
          "            PrismPasswordField(",
          "              common: const PrismFieldCommon(",
          "                name: 'password',",
          "                label: 'Password',",
          "              ),",
          "            ),",
        ];
      case 'text_field':
        final snake = _snake(label);
        return [
          "            PrismTextField(",
          "              name: '$snake',",
          "              common: PrismFieldCommon(",
          "                name: '$snake',",
          "                label: '${label.isEmpty ? 'Field' : label}',",
          "              ),",
          "            ),",
        ];
      case 'phone_field':
        return [
          "            PrismTextField.phone(",
          "              name: 'phone',",
          "              label: 'Phone number',",
          "            ),",
        ];
      case 'otp_field':
        return [
          "            PrismOtpField(",
          "              length: 6,",
          "              onCompleted: (code) {}, // TODO: verify",
          "            ),",
        ];
      case 'search_field':
        return [
          "            PrismSearch<String>(",
          "              items: const [], // your data",
          "              itemLabel: (item) => item,",
          "              onSelected: (item) {},",
          "            ),",
        ];
      case 'button':
        return [
          "            FilledButton(",
          "              onPressed: () {}, // TODO: submit",
          "              child: const Text('${label.isEmpty ? 'Submit' : label}'),",
          "            ),",
        ];
      case 'switch':
        final camel = _camel(label);
        return [
          "            PrismSwitch(",
          "              title: '${label.isEmpty ? 'Toggle' : label}',",
          "              value: _${camel}Enabled,",
          "              onChanged: (v) => setState(() => _${camel}Enabled = v),",
          "            ),",
        ];
      case 'checkbox':
        final camel = _camel(label);
        return [
          "            PrismCheckbox(",
          "              title: '${label.isEmpty ? 'Check' : label}',",
          "              value: _${camel}Checked,",
          "              onChanged: (v) => setState(() => _${camel}Checked = v),",
          "            ),",
        ];
      case 'slider':
        final camel = _camel(label);
        return [
          "            PrismSlider(",
          "              value: _${camel}Value,",
          "              label: '${label.isEmpty ? 'Slider' : label}',",
          "              onChanged: (v) => setState(() => _${camel}Value = v),",
          "            ),",
        ];
      case 'dropdown':
        final camel = _camel(label);
        return [
          "            PrismDropdown<String>(",
          "              value: _${camel}Value,",
          "              label: '${label.isEmpty ? 'Choose' : label}',",
          "              items: const [",
          "                PrismDropdownItem(value: 'one', label: 'One'),",
          "                PrismDropdownItem(value: 'two', label: 'Two'),",
          "              ],",
          "              onChanged: (v) => setState(() => _${camel}Value = v ?? _${camel}Value),",
          "            ),",
        ];
      case 'rating':
        return [
          "            PrismRating(",
          "              value: _rating,",
          "              allowHalf: true,",
          "              onChanged: (v) => setState(() => _rating = v),",
          "            ),",
        ];
      case 'calendar':
        return [
          "            PrismCalendar(",
          "              month: _focusedMonth,",
          "              selected: _selectedDays,",
          "              onDaySelected: (day) => setState(() {",
          "                _selectedDays.contains(day)",
          "                    ? _selectedDays.remove(day)",
          "                    : _selectedDays.add(day);",
          "              }),",
          "              onMonthChanged: (m) => setState(() => _focusedMonth = m),",
          "            ),",
        ];
      case 'bar_chart':
        return _cardWrapped(
          "PrismBarChart(\n                  bars: const [\n"
          "                    PrismBar(label: 'Mon', value: 12),\n"
          "                    PrismBar(label: 'Tue', value: 19),\n"
          "                    PrismBar(label: 'Wed', value: 7),\n"
          "                  ],\n                )",
        );
      case 'line_chart':
        return _cardWrapped(
          "PrismLineChart(\n                  values: const [3, 5, 4, 7, 9],\n"
          "                  labels: const ['M', 'T', 'W', 'T', 'F'],\n"
          "                )",
        );
      case 'donut_chart':
        return _cardWrapped(
          "PrismDonutChart(\n                  slices: const [\n"
          "                    PrismDonutSlice(label: 'Direct', value: 45),\n"
          "                    PrismDonutSlice(label: 'Search', value: 30),\n"
          "                    PrismDonutSlice(label: 'Social', value: 25),\n"
          "                  ],\n                  centreLabel: 'Traffic',\n"
          "                )",
        );
      case 'stat_tile':
        return [
          "            PrismCard(",
          "              child: ListTile(",
          "                title: const Text('Monthly revenue'),",
          "                subtitle: const Text('+12% vs last month'),",
          "                trailing: PrismSparkline(",
          "                  values: const [3, 5, 4, 7, 9],",
          "                  semantic: PrismSemantic.success,",
          "                ),",
          "              ),",
          "            ),",
        ];
      case 'card':
        return [
          "            PrismCard(",
          "              onTap: () {},",
          "              child: const Padding(",
          "                padding: EdgeInsets.all(16),",
          "                child: Text('${label.isEmpty ? 'Card content' : label}'),",
          "              ),",
          "            ),",
        ];
      case 'tile':
        return [
          "            PrismTile(",
          "              leading: const Icon(Icons.person_outline),",
          "              title: '${label.isEmpty ? 'Item' : label}',",
          "              subtitle: 'Tap to open',",
          "              onTap: () {},",
          "            ),",
        ];
      case 'banner':
        return [
          "            const PrismBanner(",
          "              announcements: [",
          "                PrismAnnouncement(",
          "                  id: 'welcome',",
          "                  version: 1,",
          "                  title: 'Welcome',",
          "                  message: 'Your announcement here.',",
          "                ),",
          "              ],",
          "            ),",
        ];
      case 'timeline':
        return [
          "            PrismTimeline(",
          "              entries: const [",
          "                PrismTimelineEntry(title: 'Ordered', semantic: PrismSemantic.success),",
          "                PrismTimelineEntry(title: 'Shipped', isActive: true),",
          "                PrismTimelineEntry(title: 'Delivered'),",
          "              ],",
          "            ),",
        ];
      case 'avatar':
        return [
          "            const Center(child: PrismAvatar(name: 'Ayesha Khan', size: 64)),",
        ];
      case 'progress':
        return ["            const PrismLinearProgress(value: 0.6, label: 'Loading 60%'),"];
      case 'empty_state':
        return [
          "            const PrismEmptyState(",
          "              icon: Icons.inbox_outlined,",
          "              title: 'Nothing here yet',",
          "              subtitle: 'Add something to get started.',",
          "            ),",
        ];
      case 'image':
        return [
          "            PrismZoomableImage(",
          "              imageUrl: 'https://picsum.photos/seed/prism/600/400',",
          "            ),",
        ];
      case 'file_picker':
        return [
          "            PrismFilePickerTile(",
          "              files: _files,",
          "              onPick: () async => null, // wire your picker here",
          "              onFilesPicked: (next) => setState(() => _files..clear()..addAll(next)),",
          "              onRemove: (f) => setState(() => _files.remove(f)),",
          "            ),",
        ];
      case 'image_picker':
        return [
          "            PrismImagePickerTile(",
          "              images: _images,",
          "              maxImages: 4,",
          "              onPick: () async => null, // wire your picker here",
          "              onImagesPicked: (next) => setState(() => _images..clear()..addAll(next)),",
          "              onRemove: (f) => setState(() => _images.remove(f)),",
          "            ),",
        ];
      case 'fab':
        return const []; // handled as the Scaffold FAB
      case 'chat_view':
        return [
          "            // Wire your AiStreamClient here — see the prism_kit docs.",
          "            const Center(child: Text('Chat UI goes here')),",
        ];
      default:
        return ["            // TODO: $c"];
    }
  }

  List<String> _cardWrapped(String child) => [
        "            PrismCard(",
        "              child: Padding(",
        "                padding: const EdgeInsets.all(16),",
        "                child: $child,",
        "              ),",
        "            ),",
      ];

  String _snake(String label) {
    if (label.isEmpty) return 'field';
    return label
        .split(' ')
        .map((w) => w.toLowerCase())
        .join('_')
        .replaceAll(RegExp(r'[^a-z0-9_]'), '');
  }

  String _camel(String label) {
    if (label.isEmpty) return 'value';
    final parts = label.toLowerCase().split(' ');
    final head = parts.first.replaceAll(RegExp(r'[^a-z0-9]'), '');
    final tail = parts.skip(1).map((w) {
      final clean = w.replaceAll(RegExp(r'[^a-z0-9]'), '');
      return clean.isEmpty ? '' : clean[0].toUpperCase() + clean.substring(1);
    }).join();
    final out = '$head$tail';
    return out.isEmpty ? 'value' : out;
  }
}
